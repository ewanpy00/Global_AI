package document

import (
	"fmt"
	"strings"

	"github.com/ewanpy00/Global_AI/backend/internal/verify"
)

// appendReport adds a freshness report at the end of the document: the score, then every claim
// with its verdict, current value, correction and source. applied is nil for the annotated copy
// and holds the corrected claim ids for the corrected copy.
func (s *session) appendReport(d *Doc, r *verify.Report, applied map[string]bool) error {
	w, h := 595.0, 842.0 // A4 unless the document's own pages are portrait
	if len(d.Pages) > 0 && d.Pages[0].Height > d.Pages[0].Width {
		w, h = d.Pages[0].Width, d.Pages[0].Height
	}
	wr, err := s.newWriter(w, h, 56)
	if err != nil {
		return err
	}
	para := func(text string, st style) {
		if err == nil {
			err = wr.para(text, st)
		}
	}

	para("Freshgate freshness report", style{size: 18, bold: true, color: inkText, leading: 1.2})
	pages := fmt.Sprintf("%d page%s", d.TotalPages, plural(d.TotalPages, "", "s"))
	if d.CheckedPages < d.TotalPages {
		pages = fmt.Sprintf("pages 1–%d of %d", d.CheckedPages, d.TotalPages)
	}
	para(fmt.Sprintf("%s · %s · checked %s", d.Name, pages, r.CheckedAt.UTC().Format("2 Jan 2006 15:04 UTC")),
		style{size: 9, color: inkMuted})
	wr.gap(10)

	sum := r.Summary
	if sum.Total == 0 {
		para("No time-sensitive claims found.", style{size: 14, bold: true, color: inkFresh})
	} else {
		para(fmt.Sprintf("Freshness %d/100 · %s", sum.Score, labelText[sum.Label]), style{size: 15, bold: true, color: labelInk[sum.Label]})
		para(verdictCounts(sum), style{size: 10, color: inkText})
	}
	if applied != nil {
		para(fmt.Sprintf("%d outdated statement%s rewritten in place and highlighted in green; each highlight's note keeps the original wording and the source.",
			len(applied), plural(len(applied), " was", "s were")), style{size: 9.5, color: inkMuted})
	} else if sum.Total > 0 {
		para("Highlights in the document: red = outdated or incorrect, yellow = not verified, green = confirmed current. Open a highlight to read its note.",
			style{size: 9.5, color: inkMuted})
	}
	wr.gap(14)

	for i, c := range r.Claims {
		res := c.Result
		if res == nil || err != nil {
			continue
		}
		if err = wr.keep(70); err != nil {
			break
		}
		where := "not located"
		if c.Located {
			start, _ := c.Span()
			where = fmt.Sprintf("page %d", d.pageOf(start)+1)
		}
		para(fmt.Sprintf("%d. %s · %s · freshness %d/100", i+1, strings.ToUpper(verdictText[res.Verdict]), where, res.Score),
			style{size: 10, bold: true, color: labelInk[res.Label]})
		para("“"+collapse(c.Text)+"”", style{size: 10, color: inkText, indent: 14})
		if res.CurrentValue != "" {
			now := "Now: " + res.CurrentValue
			if res.AsOf != "" {
				now += " · as of " + res.AsOf
			}
			para(now, style{size: 9.5, color: inkText, indent: 14})
		}
		if c.Fixable() {
			label := "Suggested: "
			if applied[c.ID] {
				label = "Corrected to: "
			}
			para(label+collapse(res.CorrectedText), style{size: 9.5, color: inkFresh, indent: 14})
		}
		if res.Explanation != "" {
			para(res.Explanation, style{size: 9, color: inkMuted, indent: 14})
		}
		if src := res.BestSource(); src != "" {
			para("Source: "+src, style{size: 8.5, color: inkLink, indent: 14})
		}
		wr.gap(9)
	}
	wr.gap(6)
	para("Generated by Freshgate: live web evidence from Tavily, claim extraction and verdicts by models routed through Bifrost.",
		style{size: 8, color: inkMuted})
	return err
}

func verdictCounts(sum verify.Summary) string {
	var parts []string
	for _, v := range []verify.Verdict{verify.VerdictOutdated, verify.VerdictIncorrect, verify.VerdictUnverifiable, verify.VerdictCurrent} {
		if n := sum.ByVerdict[v]; n > 0 {
			parts = append(parts, fmt.Sprintf("%d %s", n, strings.ToLower(verdictText[v])))
		}
	}
	return fmt.Sprintf("%d claims checked: %s", sum.Total, strings.Join(parts, " · "))
}

func plural(n int, one, many string) string {
	if n == 1 {
		return one
	}
	return many
}
